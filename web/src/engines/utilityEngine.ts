import { ConvertedFile } from '../types';

export async function calculateChecksums(file: File): Promise<ConvertedFile> {
  const buffer = await file.arrayBuffer();

  const [sha256Buf, sha1Buf, sha512Buf] = await Promise.all([
    crypto.subtle.digest('SHA-256', buffer),
    crypto.subtle.digest('SHA-1', buffer),
    crypto.subtle.digest('SHA-512', buffer)
  ]);

  const toHex = (buf: ArrayBuffer) =>
    Array.from(new Uint8Array(buf))
      .map((b) => b.toString(16).padStart(2, '0'))
      .join('');

  const sha256 = toHex(sha256Buf);
  const sha1 = toHex(sha1Buf);
  const sha512 = toHex(sha512Buf);

  const report = [
    `File Checksum & Cryptographic Verification Report`,
    `Generated by SFC Shadat Fatih Converter`,
    `Date: ${new Date().toISOString()}`,
    `--------------------------------------------------`,
    `File Name:    ${file.name}`,
    `File Size:    ${file.size.toLocaleString()} bytes (${formatBytes(file.size)})`,
    `MIME Type:    ${file.type || 'application/octet-stream'}`,
    `Last Modified:${new Date(file.lastModified).toLocaleString()}`,
    `--------------------------------------------------`,
    `SHA-256 Hash:`,
    sha256,
    ``,
    `SHA-1 Hash:`,
    sha1,
    ``,
    `SHA-512 Hash:`,
    sha512,
    `--------------------------------------------------`
  ].join('\n');

  const blob = new Blob([report], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const baseName = file.name.replace(/\.[^/.]+$/, '');

  return {
    name: `${baseName}_checksums.txt`,
    size: blob.size,
    type: 'text/plain',
    url,
    blob,
    previewText: report,
    extraInfo: `SHA-256: ${sha256.slice(0, 12)}...`
  };
}

export async function inspectFileMetadata(file: File): Promise<ConvertedFile> {
  const ext = file.name.split('.').pop()?.toLowerCase() || '';
  const buffer = await file.slice(0, 16).arrayBuffer();
  const hexSignature = Array.from(new Uint8Array(buffer))
    .map((b) => b.toString(16).padStart(2, '0'))
    .join(' ')
    .toUpperCase();

  const report = [
    `File Metadata & MIME Inspector`,
    `--------------------------------------------------`,
    `File Name:       ${file.name}`,
    `Extension:       .${ext}`,
    `Declared Type:   ${file.type || 'Unknown / Not declared by OS'}`,
    `File Size:       ${file.size.toLocaleString()} bytes (${formatBytes(file.size)})`,
    `Last Modified:   ${new Date(file.lastModified).toString()}`,
    `Magic Bytes:     ${hexSignature}`,
    `--------------------------------------------------`,
    `Security Note: Processed locally in sandboxed client memory.`
  ].join('\n');

  const blob = new Blob([report], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const baseName = file.name.replace(/\.[^/.]+$/, '');

  return {
    name: `${baseName}_metadata.txt`,
    size: blob.size,
    type: 'text/plain',
    url,
    blob,
    previewText: report,
    extraInfo: `Extension: .${ext} • Size: ${formatBytes(file.size)}`
  };
}

function formatBytes(bytes: number): string {
  if (bytes === 0) return '0 B';
  const k = 1024;
  const sizes = ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return `${parseFloat((bytes / Math.pow(k, i)).toFixed(2))} ${sizes[i]}`;
}
